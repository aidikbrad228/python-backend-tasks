def sort_string(s: str) -> str:
    """Возвращает новую строку с символами в порядке возрастания.

    Сортировка идёт по коду символа (Unicode), поэтому:
    - регистр учитывается: заглавные идут раньше строчных ('Z' < 'a');
    - пробелы, цифры и прочие символы тоже участвуют в сортировке.
    Исходная строка не меняется (строки в Python неизменяемы,
    sorted() создаёт новый список).
    """
    return "".join(sorted(s))